"""The rules of docs/brief.md that a grep can enforce (scshafe-qt's tests/test_rules.py).

No colour or duration literal outside the generated Swift, and glass only
through the one modifier in Sources/ScshafeComponents/Glass/.
"""

import os
import re
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LITERALS = {
    "colour literal": re.compile(
        r"\b(?:red|white|hue|green|blue):\s*[0-9.]|#colorLiteral|\b0x[0-9a-fA-F]{6,8}\b|\"#[0-9a-fA-F]{6}\""
    ),
    "duration literal": re.compile(
        r"duration:\s*[0-9]|\.(?:easeIn|easeOut|easeInOut|linear|timingCurve|spring|bouncy|smooth|snappy)\(|"
        r"\.(?:bouncy|smooth|snappy)\b"
    ),
}


def swift_sources(*roots):
    for root in roots:
        for dirpath, _, names in os.walk(os.path.join(ROOT, root)):
            for name in sorted(names):
                if name.endswith(".swift"):
                    path = os.path.join(dirpath, name)
                    with open(path, encoding="utf-8") as handle:
                        yield os.path.relpath(path, ROOT), handle.read()


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


class RulesTest(unittest.TestCase):
    def test_no_literals_outside_the_generated_files(self):
        for rel, text in swift_sources("Sources", "Tests"):
            if ".generated." in rel:
                continue
            code = strip_comments(text)
            for kind, pattern in LITERALS.items():
                with self.subTest(file=rel, rule=kind):
                    self.assertIsNone(pattern.search(code), f"{rel}: {kind}; tokens come from the registry")

    def test_glass_effect_only_in_the_glass_folder(self):
        for rel, text in swift_sources("Sources"):
            if rel.startswith("Sources/ScshafeComponents/Glass/"):
                continue
            with self.subTest(file=rel):
                self.assertNotIn("glassEffect(", strip_comments(text), f"{rel}: use .suiGlass")

    def test_generated_files_carry_their_header(self):
        for rel, text in swift_sources("Sources", "Tests"):
            if ".generated." in rel:
                with self.subTest(file=rel):
                    self.assertTrue(text.startswith("// GENERATED by tools/gen_tokens.py"))

    def test_no_compatibility_opt_out(self):
        for rel, text in swift_sources("Sources", "Tests"):
            with self.subTest(file=rel):
                self.assertNotIn("UIDesignRequiresCompatibility", text)

    def test_no_application_names(self):
        for rel, text in swift_sources("Sources"):
            with self.subTest(file=rel):
                self.assertIsNone(re.search(r"homemesh|parley|mailroom|jobtrack", text, re.I))


if __name__ == "__main__":
    unittest.main()
